package com.soulbot.app

/**
 * De-identified regression examples derived from observed failure patterns.
 * Wording and profile details are paraphrased; this corpus is evaluation-only,
 * never a source of facts or approved style examples for live conversations.
 */
internal data class ChatRegressionMessage(
    val role: String,
    val text: String,
    val context: String,
    val intent: String,
)

internal data class ChatRegressionCase(
    val id: String,
    val title: String,
    val scene: ReplyScene,
    val messages: List<ChatRegressionMessage>,
    val observedFailure: String,
    val failureType: String,
    val expectedBehavior: String,
    val idealReply: String,
) {
    fun asReplayCase() = ReplyReplayCase(
        id = id,
        contact = "",
        scene = scene,
        turns = messages.map { ReplayTurn(it.role, it.text) },
        originalReply = observedFailure,
        reason = expectedBehavior,
        dataset = ReplayDataset.EVALUATION,
    )
}

